from typing import Protocol

from app.retrieval.bm25 import BM25Retriever
from app.retrieval.fusion import reciprocal_rank_fusion
from app.retrieval.models import SearchResult
from app.retrieval.reranker import NoOpReranker, TextReranker
from app.retrieval.tfidf import split_text
from app.retrieval.vectorizer import TextVectorizer


class VectorRepository(Protocol):
    async def add_document(
        self,
        filename: str,
        chunk_texts: list[str],
        embeddings: list[list[float]],
        *,
        embedding_model: str,
    ) -> str: ...

    async def remove_document(self, doc_id: str) -> bool: ...

    async def list_chunks(self) -> list[SearchResult]: ...

    async def has_stale_embeddings(self, embedding_model: str) -> bool: ...

    async def search(
        self,
        query_embedding: list[float],
        *,
        top_k: int,
        min_score: float,
    ) -> list[SearchResult]: ...

    async def update_embeddings(
        self,
        embeddings: dict[str, list[float]],
        *,
        embedding_model: str,
    ) -> None: ...


class StaleEmbeddingError(RuntimeError):
    """Raised when stored vectors were generated by a different embedding model."""


class VectorRetriever:
    def __init__(
        self,
        repository: VectorRepository,
        embedding_client: TextVectorizer,
        *,
        chunk_size: int,
        chunk_overlap: int,
        candidate_k: int = 30,
        rrf_k: int = 60,
        reranker: TextReranker | None = None,
    ) -> None:
        if candidate_k <= 0:
            raise ValueError("candidate_k must be positive")
        if rrf_k <= 0:
            raise ValueError("rrf_k must be positive")
        self._repository = repository
        self._embedding_client = embedding_client
        self._chunk_size = chunk_size
        self._chunk_overlap = chunk_overlap
        self._candidate_k = candidate_k
        self._rrf_k = rrf_k
        self._bm25 = BM25Retriever()
        self._reranker = reranker or NoOpReranker()

    async def index_document(self, filename: str, content: str) -> tuple[str, int]:
        chunks = split_text(
            content,
            chunk_size=self._chunk_size,
            overlap=self._chunk_overlap,
        )
        if not chunks:
            raise ValueError("document contains no indexable text")
        vectors = await self._embedding_client.embed(chunks, input_kind="passage")
        doc_id = await self._repository.add_document(
            filename,
            chunks,
            vectors,
            embedding_model=self._embedding_client.model_id,
        )
        return doc_id, len(chunks)

    async def remove_document(self, doc_id: str) -> bool:
        return await self._repository.remove_document(doc_id)

    async def search(
        self,
        query: str,
        *,
        top_k: int,
        min_score: float,
    ) -> list[SearchResult]:
        if top_k <= 0:
            return []
        chunks = await self._repository.list_chunks()
        if not chunks:
            return []
        if await self._repository.has_stale_embeddings(self._embedding_client.model_id):
            raise StaleEmbeddingError(
                "stored vectors use another embedding model; run "
                "python -m app.retrieval.rebuild_embeddings first"
            )

        query_vector = (await self._embedding_client.embed([query], input_kind="query"))[0]
        dense_results = await self._repository.search(
            query_vector,
            top_k=self._candidate_k,
            min_score=0.0,
        )
        lexical_results = self._bm25.search(query, chunks, top_k=self._candidate_k)
        fused_results = reciprocal_rank_fusion(
            [dense_results, lexical_results],
            rrf_k=self._rrf_k,
            limit=self._candidate_k,
        )
        reranked_results = await self._reranker.rerank(query, fused_results)
        return [result for result in reranked_results if result.score >= min_score][:top_k]

    async def rebuild_embeddings(self, *, batch_size: int = 64) -> int:
        if batch_size <= 0:
            raise ValueError("batch_size must be positive")
        chunks = await self._repository.list_chunks()
        for offset in range(0, len(chunks), batch_size):
            batch = chunks[offset : offset + batch_size]
            vectors = await self._embedding_client.embed(
                [chunk.text for chunk in batch],
                input_kind="passage",
            )
            if len(vectors) != len(batch):
                raise ValueError("embedding model returned a different number of vectors")
            await self._repository.update_embeddings(
                {chunk.chunk_id: vector for chunk, vector in zip(batch, vectors, strict=True)},
                embedding_model=self._embedding_client.model_id,
            )
        return len(chunks)
